"""Build an offline shared font registry, verifying font data and licenses."""
import base64
import hashlib
import json
from pathlib import Path
import re
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / 'dist/vendor/fonts'
manifest = json.loads((FONTS / 'manifest.json').read_text())
files, source_ids, axes, details, sources = {}, {}, {}, {}, {}
core_families = {'Inter', 'Space Grotesk', 'JetBrains Mono'}
core_ids = set()
def checked(record):
    data = (FONTS / record['file']).read_bytes()
    if hashlib.sha256(data).hexdigest() != record['sha256']:
        raise ValueError('Font cache integrity failure: ' + record['file'])
    return data

for record in manifest['fonts']:
    data = checked(record)
    key = record['sha256']
    source_ids[record['url']] = key
    sources[key] = {'url':record['url'], 'bytes':len(data)}
    if key not in files:
        font = TTFont(FONTS / record['file'])
        axes[key] = {a.axisTag: [a.minValue, a.maxValue] for a in font['fvar'].axes} if 'fvar' in font else {}
        details[key] = {'family':font['name'].getDebugName(1), 'axes':axes[key], 'glyphs':len(font.getBestCmap() or {})}
        files[key] = base64.b64encode(data).decode('ascii')
        font.close()

licenses = {r['family']: checked(r).decode('utf-8') for r in manifest['licenses']}
sheets = {}
before_count, after_count = 0, 0
for record in manifest['stylesheets']:
    css = checked(record).decode('utf-8')
    groups = {}
    for block in re.findall(r'@font-face\s*\{([^}]+)\}', css):
        props = dict(part.strip().split(':',1) for part in block.split(';') if ':' in part)
        props = {k.strip():v.strip() for k,v in props.items()}
        url = re.search(r'url\(([^)]+)\)',props['src'])[1]
        key = source_ids[url]
        if props['font-family'].strip('\'"') in core_families:
            core_ids.add(key)
        props['src'] = f'url("studio-font:{key}") format("woff2")'
        before_count += 1
        weight = props['font-weight']
        variable = axes[key].get('wght')
        # Only merge separate weight rules after reading the binary's fvar
        # axis. Static fonts keep their original individual face descriptors.
        mergeable = variable and re.fullmatch(r'\d+',weight) and variable[0] <= int(weight) <= variable[1]
        grouping = tuple(sorted((k,v) for k,v in props.items() if k != 'font-weight' or not mergeable))
        if grouping not in groups:
            groups[grouping] = [props, set()]
        if mergeable:
            groups[grouping][1].add(int(weight))
    families = sorted({p['font-family'].strip('\'"') for p,_ in groups.values()})
    license_text = '\n\n'.join(f'{family}\n{licenses[family]}' for family in families)
    content = ['/* Bundled template fonts. Licenses:\n' + license_text.replace('*/','* /').replace('</style','<\\/style') + '\n*/']
    face_descriptors = []
    for props,weights in groups.values():
        if len(weights) > 1:
            props['font-weight'] = f'{min(weights)} {max(weights)}'
        content.append('@font-face{' + ';'.join(k+':'+v for k,v in props.items()) + '}')
        face_descriptors.append({k:props[k].strip('\'"') for k in ['font-family','font-style','font-weight','unicode-range'] if k in props})
    after_count += len(groups)
    sheets[record['url']] = {'css':'\n'.join(content), 'families':families, 'faces':face_descriptors}

summary = {'families':manifest['families'], 'sourceFiles':len(manifest['fonts']), 'uniqueFiles':len(files),
           'bytes':sum(len(base64.b64decode(v)) for v in files.values()), 'sourceFaces':before_count, 'mergedFaces':after_count,
           'embeddedFamilies':sorted(core_families), 'embeddedFiles':len(core_ids),
           'embeddedBytes':sum(sources[key]['bytes'] for key in core_ids)}
out = '// Generated by scripts/build-template-fonts.py. Font licenses are retained in each stylesheet.\n'
for name,value in [('bundledFontFiles',{k:v for k,v in files.items() if k in core_ids}),('bundledFontSources',sources),('bundledFontStylesheets',sheets),('bundledFontSummary',summary)]:
    out += 'export const '+name+' = '+json.dumps(value,ensure_ascii=False,separators=(',',':'))+';\n'
(ROOT/'dist/template-font-data.js').write_text(out)
(FONTS/'build-report.json').write_text(json.dumps({'summary':summary,'files':details},ensure_ascii=False,indent=2)+'\n')
print(json.dumps(summary,ensure_ascii=False))
